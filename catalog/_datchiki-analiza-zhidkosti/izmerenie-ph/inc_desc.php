<h2>Устройство и принцип работы</h2>
<p>
	 Анализ уровня pH основан на измерении активности ионов водорода в жидкости. Сам термин pH расшифровывается как «pondus hydrogenii» — «вес водорода». Измерение производится по ионометрическому методу с использованием стеклянного электрода, определяющего электродвижущую силу, пропорциональную водородному показателю.
</p>
<p>
	 Технически pH-метр — это вольтметр, измеряющий разность потенциалов между двумя электродами, погружёнными в среду. Некоторые модели оснащены комбинированным электродом, встроенным в корпус для защиты от внешней среды и механических повреждений.
</p>
