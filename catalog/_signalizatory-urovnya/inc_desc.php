<h2>Применение сигнализаторов уровня для жидких сред</h2>
<p>
 <strong>Поплавковые</strong>
</p>
<p>
	 Один из самых экономичных и надежных решений для контроля и сигнализации предельного уровня воды и стоков. Они напрямую контактируют с жидкостью, с высокой точностью определяя уровень заполнения или опустошения сосуда. Пример поплавкового сигнализатора уровня — <a href="/product/nivofloat-poplavkovyy-signalizator-urovnya/">датчик контроля уровня жидкостей NIVOFLOAT</a>.
</p>
<p>
 <strong>Применение: </strong>
</p>
<p>
	 для защиты от холостого хода насоса; для управления наполнением/опустошением резервуара; как датчик контроля уровня воды; как датчик включения или отключения насоса; как датчик уровня воды в колодце, бассейне; для контроля сточных вод промышленного и коммунального назначения.
</p>
<p>
 <strong>Кондуктивные&nbsp;</strong>
</p>
<p>
	 Данный тип датчиков нечувствителен к турбулентности, но в то же время прост в настройке и обслуживании. У кондуктометрических сигнализаторов отсутствуют движущиеся механические элементы, поэтому они способны бесперебойно работать в среде с высоким давлением и переменчивой температурой.
</p>
<p>
	 Пример — <a href="/product/nivocont-k-konduktivnyy-signalizator-urovnya/">NIVOCONT K</a>.
</p>
<p>
 <strong>Применение: </strong>
</p>
<ul>
	<li><a href="/industries/29/">фармацевтика</a>;</li>
	<li><a href="/industries/29/">химическая промышленность</a>;</li>
	<li>коммунальное и сельское хозяйство;</li>
	<li><a href="/industries/produkty-pitaniya/">пищепром</a>;</li>
	<li><a href="/industries/28/">энергетический комплекс</a>.</li>
</ul>
<p>
 <strong>Магнитные</strong>
</p>
<p>
	 Одни из самых неприхотливых приборов для измерения уровня жидкости, поэтому они могут эксплуатироваться в любой среде. Подходят под любую систему управления. Энергонезависимы и автономны, не требуют калибровки. Доступная цена&nbsp;делает их одними из самых популярных приборов. В нашем ассортименте представлены магнитные сигнализаторы <a href="/product/nivomag-magnitnyy-signalizator-urovnya/">NIVOMAG</a> и <a href="/product/nivopoint-poplavkovyy-magnitnyy-signalizator-urovnya/">NIVOPOINT</a>.
</p>
<p>
 <strong>Где используются: </strong>
</p>
<ul>
	<li><a href="/industries/35/">нефтяная и топливная промышленность</a>;</li>
	<li><a href="/industries/produkty-pitaniya/">пищепром</a>;</li>
	<li><a href="/industries/27/">строительство</a>;</li>
	<li>ЖКХ;</li>
	<li><a href="/industries/30/">станции водоочистки</a>;</li>
	<li><a href="/industries/29/">фармацевтическая и химическая промышленность</a>;</li>
	<li>коррозийные среды.</li>
</ul>
<p>
 <strong>Вибрационные</strong>
</p>
<p>
	 Определяют уровень наполнения или опустошения резервуара жидким продуктом по изменению амплитуды механических резонансных колебаний чувствительного элемента. Простая конструкция датчиков с защищенным корпусом позволяет использовать устройства в разных средах. Они не требуют технического обслуживания и просто устанавливаются.
</p>
<p>
	 Пример — <a href="/product/nivoswitch-dlya-zhidkostey-vibracionnyy-signalizator-urovnya/">NIVOSWITCH</a> (имеет модификацию и для сыпучих сред).
</p>
<p>
 <strong>Сферы применения: </strong>
</p>
<ul>
	<li><a href="/industries/produkty-pitaniya/">пищевая промышленность</a>;</li>
	<li><a href="/industries/29/">химическая промышленность</a>;</li>
	<li><a href="/industries/30/">ЖКХ: водоснабжение, водоподготовка, водоотведение</a>;</li>
	<li><a href="/industries/28/">энергетический комплекс</a>;</li>
	<li><a href="/industries/29/">фармацевтика</a>;</li>
	<li><a href="/industries/35/">нефтедобывающая промышленность</a>.</li>
</ul>
<p>
 <strong>Емкостные</strong>
</p>
<p>
	 Работают с разными жидкостями, в том числе с минимальной диэлектрической проницаемостью. Емкостные датчики измерения уровня сохраняют высокую точность в рабочей емкости с высоким давлением и широким диапазоном температуры.
</p>
<p>
	 Пример — <a href="/product/nivocap-ck-emkostnoy-signalizator-urovnya/">NIVOCAP CK</a> (имеет модификацию и для сыпучих сред).
</p>
<p>
	 Однако стоит учесть и некоторые ограничения в работе этих приборов. Для того чтобы емкостные сигнализаторы показывали точные данные, необходимо тщательно регулировать чувствительность и рабочие параметры устройства под каждый исследуемый продукт. Используя&nbsp;в среде, склонной к повышенному пенообразованию, учтите это при настройке.
</p>
<h2>Виды сигнализаторов уровня для сыпучих сред. Применение</h2>
<p>
 <strong>Ротационные</strong>
</p>
<p>
	 Применяются для работы со всеми видами твердых сыпучих материалов. Способны измерять уровень материала даже в условиях высокой запыленности, при которых использование других приборов недостаточно эффективно. Одним из весомых плюсов этих устройств является высокая стабильность срабатывания. В нашем ассортименте представлены&nbsp;<a href="/product/nivorota-rotacionnyy-signalizator-urovnya/">сигнализаторы NIVOROTA</a> во взрывобезопасном исполнении для агрессивных сред.
</p>
<p>
 <strong>Где используется: </strong>
</p>
<ul>
	<li>аграрный комплекс;</li>
	<li><a href="/industries/produkty-pitaniya/">пищепром</a>;</li>
	<li><a href="/industries/27/">строительство</a>;</li>
	<li><a href="/industries/35/">химическая промышленность</a>;</li>
	<li>деревообработка;</li>
	<li><a href="/industries/29/">фармацевтическая промышленность</a>.</li>
</ul>
<p>
 <strong>Вибрационные</strong>
</p>
<p>
	 Сигнализируют о достижении определенного уровня по изменению амплитуды механических резонансных колебаний чувствительного элемента датчика. Существуют датчики в пыле-, взрывозащищенном, гигиеническом исполнениях, что позволяет выбрать прибор под конкретные задачи компании. Точность&nbsp;не зависит от температуры, давления, видимости, проводимости и других характеристик среды.
</p>
<p>
	 Пример — <a href="/product/nivoswitch-dlya-sypuchikh-materialov-vibracionnyy-signalizator-urovnya/">NIVOSWITCH</a>.
</p>
<p>
 <strong>Где используются: </strong>
</p>
<ul>
	<li><a href="/industries/produkty-pitaniya/">пищевая промышленность</a>;</li>
	<li><a href="/industries/27/">строительная индустрия</a>;</li>
	<li>полимерная промышленность;</li>
	<li>производство комбикормов;</li>
	<li>деревообработка.</li>
</ul>
<p>
	 В каталоге компании “Анкорн” существуют различные модификации приборов контроля и измерения уровня, использующих различные физические методы.
</p>
<p>
	 Когда выбираете датчик не забудьте учесть все свойства среды измерения:
</p>
<ul>
	<li>температуру,</li>
	<li>абразивность,</li>
	<li>вязкость вещества,</li>
	<li>электропроводимость,</li>
	<li>агрессивность среды,</li>
	<li>давление,</li>
	<li>вакуум,</li>
	<li>нагревание/охлаждение,</li>
	<li>способ заполнения/опустошения резервуара,</li>
	<li>взрывоопасность и прочие.</li>
