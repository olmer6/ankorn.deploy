<h2>Купить сигнализатор уровня жидкости в компании “АНКОРН”</h2>
<p>
	 Часто на производствах, в резервуарах, подключаются сигнализаторы уровня жидкости. С помощью этих датчиков организовывается многоуровневая схема контроля: заполнение и опустошение емкости, сигнализация о переполнении и аварийной остановке и т.д.
</p>
<p>
	 Датчик-реле обеспечивает предупреждение о достижении уровня чистых или сточных вод, нефтепродуктов, различного вида масел, молока, соков, соусов, шоколада и пр.
</p>
